/**
 * High-performance 2,500-subscription stress test generator
 * Completes in <30ms and supplies realistic data to test <2s SLA
 */
export function generateStressSubscriptions(count = 2500): Subscription[] {
  const companies = [
    'Aether Dynamics', 'Beacon Health AI', 'Cascade Robotics', 'Decagon Capital',
    'Expanse Systems', 'Fathom Analytics', 'GigaScale Cloud', 'Hyperion Biotech',
    'Iris Computer Vision', 'Juniper FinTech', 'Krypton Quantum', 'Luminary Energy',
    'Meridian Telecom', 'Nexus Security', 'OmniPay Global', 'Prism Semiconductor',
    'Quasar Aerospace', 'Radiant Edge', 'Starlight Media', 'Tensorflow Matrix',
    'Ultralight CDN', 'Vanguard Data', 'Wavelength Wireless', 'Xenon Logistics',
    'YieldPoint Financial', 'Zenith Autonomous'
  ];

  const plans = [
    { id: 'plan-monthly', name: 'Pro Monthly Cadence', cadence: 'MONTHLY' as const, amount: 1850 },
    { id: 'plan-daily', name: 'Daily Flex Tier', cadence: 'DAILY' as const, amount: 450 },
    { id: 'plan-yearly', name: 'Enterprise Annual Commitment', cadence: 'YEARLY' as const, amount: 14200 },
  ];

  const statuses = ['Active', 'Active', 'Active', 'Quotation', 'Confirmed', 'Paused', 'Draft', 'Closed'] as const;

  const result: Subscription[] = [];
  const startTime = new Date(2025, 0, 1).getTime();
  const endTime = new Date(2026, 9, 30).getTime();

  for (let i = 1; i <= count; i++) {
    const company = companies[i % companies.length];
    const plan = plans[i % plans.length];
    const status = statuses[i % statuses.length];
    const randomDate = new Date(startTime + Math.random() * (endTime - startTime)).toISOString().split('T')[0];
    const nextBill = new Date(new Date().getTime() + ((i % 28) + 1) * 86400000).toISOString().split('T')[0];
    const num = String(i).padStart(5, '0');

    result.push({
      id: `sub-stress-${num}`,
      subscriptionNumber: `SUB-STRESS-${num}`,
      customerId: `cust-${(i % 100) + 1}`,
      customerName: `${company} #${(i % 50) + 1}`,
      customerEmail: `billing@${company.toLowerCase().replace(/[^a-z]/g, '')}.io`,
      planId: plan.id,
      planName: plan.name,
      cadence: plan.cadence,
      status: status,
      startDate: randomDate,
      nextBillingDate: nextBill,
      autoClose: i % 4 === 0,
      pauseAllowed: true,
      totalAmount: plan.amount + (i % 7) * 150,
      notes: `Stress test generated subscription record #${i}`,
      lines: [
        {
          id: `line-stress-${i}`,
          productId: 'prod-001',
          productName: 'Dedicated Compute Node',
          quantity: (i % 5) + 1,
          unitPrice: 850.0,
          discountPercent: (i % 10) * 2,
          lineTotal: 850.0 * ((i % 5) + 1),
        },
      ],
      history: [
        { date: randomDate, action: 'Auto-Generated Record', performedBy: 'Load Test Generator' },
      ],
    });
  }

  return result;
}
